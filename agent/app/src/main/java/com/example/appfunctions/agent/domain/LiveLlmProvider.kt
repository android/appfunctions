package com.example.appfunctions.agent.domain

import androidx.appfunctions.metadata.AppFunctionMetadata
import com.example.appfunctions.agent.data.GeminiLiveVoice
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.withContext

/** Default microphone PCM input sample rate in Hz for live audio sessions. */
const val DEFAULT_LIVE_INPUT_SAMPLE_RATE_HZ = 16_000

/** Default model PCM output sample rate in Hz for live audio sessions. */
const val DEFAULT_LIVE_OUTPUT_SAMPLE_RATE_HZ = 24_000

/** Interface for LLM providers supporting bidirectional realtime audio and tool sessions. */
interface LiveLlmProvider {
    /**
     * Connects to the live LLM backend, completes session initialization with [tools] and [voice],
     * and returns the active [LiveLlmSession]. The caller is responsible for closing the returned
     * session via [LiveLlmSession.close] or using [withSession].
     */
    suspend fun connect(
        apiKey: String,
        tools: List<AppFunctionMetadata>,
        voice: GeminiLiveVoice = GeminiLiveVoice.DEFAULT,
    ): LiveLlmSession
}

/**
 * Connects to the [LiveLlmProvider], invokes [block] with the active [LiveLlmSession], and ensures
 * [LiveLlmSession.close] is called when [block] completes or is cancelled.
 */
suspend inline fun LiveLlmProvider.withSession(
    apiKey: String,
    tools: List<AppFunctionMetadata>,
    voice: GeminiLiveVoice = GeminiLiveVoice.DEFAULT,
    block: (LiveLlmSession) -> Unit,
) {
    val session = connect(apiKey = apiKey, tools = tools, voice = voice)
    try {
        block(session)
    } finally {
        withContext(NonCancellable) {
            session.close()
        }
    }
}

/** Represents an active bidirectional voice and tool session with an LLM provider. */
interface LiveLlmSession {
    /** Sequential stream of server-originated events for this live session. */
    val events: Flow<LiveLlmEvent>

    /**
     * Sends a chunk of raw 16-bit mono PCM user microphone audio at [sampleRateHz] to the model.
     */
    suspend fun sendAudio(
        pcmBytes: ByteArray,
        sampleRateHz: Int = DEFAULT_LIVE_INPUT_SAMPLE_RATE_HZ,
    )

    /**
     * Sends tool execution [outputs] back to the model in response to a
     * [LiveLlmEvent.ToolCallRequest].
     */
    suspend fun sendToolResponses(outputs: List<ToolOutput>)

    /** Closes the live session and releases the underlying transport connection. */
    suspend fun close()
}

/** Provider-agnostic events emitted by a [LiveLlmSession]. */
sealed class LiveLlmEvent {
    /** Indicates the user interrupted the model's current audio response. */
    object Interrupted : LiveLlmEvent()

    /** Incremental speech-to-text transcription of the user's audio input. */
    data class InputTranscription(val text: String) : LiveLlmEvent()

    /** Incremental transcription of the model's spoken response. */
    data class OutputTranscription(val text: String) : LiveLlmEvent()

    /** Raw 16-bit mono PCM audio chunk generated by the model for playback at [sampleRateHz]. */
    data class AudioChunk(
        val pcmBytes: ByteArray,
        val sampleRateHz: Int = DEFAULT_LIVE_OUTPUT_SAMPLE_RATE_HZ,
    ) : LiveLlmEvent() {
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (other !is AudioChunk) return false
            return pcmBytes.contentEquals(other.pcmBytes) && sampleRateHz == other.sampleRateHz
        }

        override fun hashCode(): Int {
            var result = pcmBytes.contentHashCode()
            result = 31 * result + sampleRateHz
            return result
        }
    }

    /** Indicates the model finished its current conversational turn. */
    object TurnComplete : LiveLlmEvent()

    /** Requests execution of one or more [calls] before continuing the live conversation. */
    data class ToolCallRequest(val calls: List<LlmResponsePart.ToolCall>) : LiveLlmEvent()

    /** Indicates an error occurred during the live session. */
    data class Error(
        val message: String,
        val cause: Throwable? = null,
    ) : LiveLlmEvent()
}
