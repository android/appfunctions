package com.example.appfunctions.agent.domain

import androidx.appfunctions.metadata.AppFunctionMetadata
import kotlinx.coroutines.flow.Flow

/** Interface for LLM providers supporting bidirectional realtime audio and tool sessions. */
interface LiveLlmProvider {
    /**
     * Connects to the live LLM backend, completes session initialization with [tools], and invokes
     * [block] with an active [LiveLlmSession] until [block] returns or is cancelled.
     */
    suspend fun connect(
        apiKey: String,
        tools: List<AppFunctionMetadata>,
        block: suspend (LiveLlmSession) -> Unit,
    )
}

/** Represents an active bidirectional voice and tool session with an LLM provider. */
interface LiveLlmSession {
    /** Sequential stream of server-originated events for this live session. */
    val events: Flow<LiveLlmEvent>

    /** Sends a chunk of raw 16-bit 16kHz mono PCM user microphone audio to the model. */
    suspend fun sendAudio(pcmBytes: ByteArray)

    /** Sends tool execution [outputs] back to the model in response to a [LiveLlmEvent.ToolCallRequest]. */
    suspend fun sendToolResponses(outputs: List<ToolOutput>)
}

/** Provider-agnostic events emitted by a [LiveLlmSession]. */
sealed class LiveLlmEvent {
    /** Indicates the user interrupted the model's current audio response. */
    object Interrupted : LiveLlmEvent()

    /** Incremental speech-to-text transcription of the user's audio input. */
    data class InputTranscription(val text: String) : LiveLlmEvent()

    /** Incremental transcription of the model's spoken response. */
    data class OutputTranscription(val text: String) : LiveLlmEvent()

    /** Raw PCM audio chunk generated by the model for playback. */
    data class AudioChunk(val pcmBytes: ByteArray) : LiveLlmEvent()

    /** Indicates the model finished its current conversational turn. */
    object TurnComplete : LiveLlmEvent()

    /** Requests execution of one or more [calls] before continuing the live conversation. */
    data class ToolCallRequest(val calls: List<LlmResponsePart.ToolCall>) : LiveLlmEvent()
}
